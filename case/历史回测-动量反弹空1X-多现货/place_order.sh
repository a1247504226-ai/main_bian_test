#!/usr/bin/env bash
# 手动下单（等价于 Windows 的「一键下单.bat」）
# 两段式：先演练（不发单）→ 你输入 Y 才真下
#
#   bash place_order.sh              演练 + 询问
#   bash place_order.sh --rebalance  一次性把旧仓位对齐到当前敞口（改过 vt/cap 后用一次）
#   bash place_order.sh --testnet    强制连测试网
#
# 注意：--live 由本脚本自动加，你不用手动传。
set -u
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR" || exit 1
PY="$(command -v python3 || command -v python || true)"
if [ -z "$PY" ]; then
    echo "[ERROR] 找不到 python3，请先安装"
    exit 1
fi

# 过滤掉用户可能误传的 --live（本脚本自己控制）
ARGS=()
for a in "$@"; do
    [ "$a" = "--live" ] || ARGS+=("$a")
done

echo "================================================================================"
echo " STEP 1/2  演练（不会发出任何订单）"
echo "================================================================================"
echo
"$PY" btc_trade.py "${ARGS[@]+"${ARGS[@]}"}"
RC=$?
if [ "$RC" != "0" ]; then
    echo
    echo "================================================================================"
    echo " 演练失败（退出码 $RC），未下单。请按上面的提示修好后重跑。"
    echo "================================================================================"
    exit "$RC"
fi

echo
echo "--------------------------------------------------------------------------------"
echo " 上面只是计划，什么都还没发出去。"
echo "--------------------------------------------------------------------------------"
echo
printf '输入 Y 回车 → 真实下单；直接回车 → 取消： '
read -r ANS
case "$ANS" in
    Y|y) ;;
    *) echo "已取消，未下单。"; exit 0 ;;
esac

echo
echo "================================================================================"
echo " STEP 2/2  真实下单"
echo "================================================================================"
echo
"$PY" btc_trade.py --live "${ARGS[@]+"${ARGS[@]}"}"
RC=$?
echo
if [ "$RC" = "0" ]; then
    echo "================================================================================"
    echo " 完成：仓位已与策略目标对齐。"
    echo " 交易流水：$DIR/trade_log.csv"
    echo " 最近状态：$DIR/trade_state.json"
    echo "================================================================================"
else
    echo "================================================================================"
    echo " 失败（退出码 $RC）—— 看 trade_log.csv 和上面的提示。"
    echo " 重跑是安全的：它是对账模式，不会翻倍下单。"
    echo "================================================================================"
fi
exit "$RC"
